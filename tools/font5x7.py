def glyph(ch):
    """Return the glyph rows for a character (lowercase falls back to uppercase)."""
    if ch in GLYPHS:
        return GLYPHS[ch]
    up = ch.upper()
    if up in GLYPHS:
        return GLYPHS[up]
    return GLYPHS["?"]


def draw_text(img, x, y, text, color, scale=1, shadow=None, spacing=1):
    """Draw text into a PIL image using the 5x7 glyphs."""
    px = img.load()
    w, h = img.size
    cx = x
    for ch in text:
        rows = glyph(ch)
        for ry, row in enumerate(rows):
            for rx, c in enumerate(row):
                if c != "#":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        if shadow is not None:
                            qx = cx + rx * scale + sx + scale
                            qy = y + ry * scale + sy + scale
                            if 0 <= qx < w and 0 <= qy < h:
                                px[qx, qy] = shadow
        for ry, row in enumerate(rows):
            for rx, c in enumerate(row):
                if c != "#":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        qx = cx + rx * scale + sx
                        qy = y + ry * scale + sy
                        if 0 <= qx < w and 0 <= qy < h:
                            px[qx, qy] = color
        cx += (5 + spacing) * scale
    return cx


def text_width(text, scale=1, spacing=1):
    return len(text) * (5 + spacing) * scale - spacing * scale
